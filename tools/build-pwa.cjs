/*
 Builds the offline files for POME Lab: icons, manifest and sw.js.
 Run after changing files or bumping the ?v= version:  node tools/build-pwa.cjs
 The service worker precaches every page, script, style and image (except the large
 gesture-camera models, which are cached the first time the camera is used).
*/
const fs=require('fs'),path=require('path'),zlib=require('zlib'),{execSync}=require('child_process');
const root=path.join(__dirname,'..');process.chdir(root);

/* ---- icons: a small PNG encoder, lime droplet on dark green ---- */
function png(size){
 const px=Buffer.alloc(size*size*4);
 for(let y=0;y<size;y++)for(let x=0;x<size;x++){
  const u=x/size,v=y/size,i=(y*size+x)*4;let r=12,g=38,b=32,a=255;
  // rounded square background
  const m=.18,cx=Math.min(Math.max(u,m),1-m),cy=Math.min(Math.max(v,m),1-m);if(Math.hypot(u-cx,v-cy)>m){a=0}
  // droplet: circle + triangle tip
  const dx=u-.5,dy=v-.58,inCircle=Math.hypot(dx,dy)<.24,inTip=v>.16&&v<.42&&Math.abs(dx)<(v-.16)*.85;
  if(a&&(inCircle||inTip)){r=217;g=245;b=138}
  // leaf highlight
  if(a&&Math.hypot(u-.42,v-.6)<.07){r=20;g=52;b=43}
  px[i]=r;px[i+1]=g;px[i+2]=b;px[i+3]=a}
 const raw=Buffer.alloc(size*(size*4+1));for(let y=0;y<size;y++){raw[y*(size*4+1)]=0;px.copy(raw,y*(size*4+1)+1,y*size*4,(y+1)*size*4)}
 const crcT=Array.from({length:256},(_,n)=>{let c=n;for(let k=0;k<8;k++)c=c&1?0xedb88320^(c>>>1):c>>>1;return c>>>0});
 const crc=b=>{let c=0xffffffff;for(const x of b)c=crcT[(c^x)&255]^(c>>>8);return (c^0xffffffff)>>>0};
 const chunk=(t,d)=>{const l=Buffer.alloc(4);l.writeUInt32BE(d.length);const td=Buffer.concat([Buffer.from(t),d]);const c=Buffer.alloc(4);c.writeUInt32BE(crc(td));return Buffer.concat([l,td,c])};
 const ihdr=Buffer.alloc(13);ihdr.writeUInt32BE(size,0);ihdr.writeUInt32BE(size,4);ihdr[8]=8;ihdr[9]=6;
 return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',ihdr),chunk('IDAT',zlib.deflateSync(raw,{level:9})),chunk('IEND',Buffer.alloc(0))]);
}
fs.mkdirSync('icons',{recursive:true});
for(const s of [192,512])fs.writeFileSync(`icons/icon-${s}.png`,png(s));

/* ---- manifest ---- */
fs.writeFileSync('manifest.webmanifest',JSON.stringify({
 name:'POME Lab — Effluent to opportunity',short_name:'POME Lab',lang:'ms',
 description:'Interactive palm oil mill effluent treatment lab for secondary-school learners.',
 start_url:'./index.html',scope:'./',display:'standalone',background_color:'#0d1717',theme_color:'#102b24',
 icons:[{src:'icons/icon-192.png',sizes:'192x192',type:'image/png',purpose:'any maskable'},{src:'icons/icon-512.png',sizes:'512x512',type:'image/png',purpose:'any maskable'}]
},null,1));

/* ---- service worker ---- */
const files=execSync('git ls-files',{encoding:'utf8'}).split('\n').filter(f=>f&&!/^(tools\/|README|\.|sw\.js$)/.test(f)&&!/gesture\/vendor\//.test(f)&&!/\.test\./.test(f));
for(const extra of ['manifest.webmanifest','icons/icon-192.png','icons/icon-512.png'])if(!files.includes(extra))files.push(extra);
const hash=require('crypto').createHash('sha1');for(const f of files.sort())hash.update(f+fs.statSync(f).size+fs.statSync(f).mtimeMs);
const version=hash.digest('hex').slice(0,10);
fs.writeFileSync('sw.js',`/* POME Lab offline cache. Generated by tools/build-pwa.cjs — do not edit by hand. */
const VERSION='pome-${version}';
const PRECACHE=${JSON.stringify(['./',...files.map(f=>'./'+f)])};
self.addEventListener('install',e=>{e.waitUntil(caches.open(VERSION).then(c=>c.addAll(PRECACHE)).then(()=>self.skipWaiting()))});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('pome-')&&k!==VERSION).map(k=>caches.delete(k)))).then(()=>self.clients.claim()))});
// Pages (navigation): network first so learners always get the latest version when online; cache when offline.
self.addEventListener('fetch',e=>{const req=e.request;if(req.mode!=='navigate'||new URL(req.url).origin!==location.origin)return;
 e.respondWith(fetch(req).then(res=>{if(res.ok){const copy=res.clone();caches.open(VERSION).then(c=>c.put(req,copy))}return res}).catch(()=>caches.open(VERSION).then(c=>c.match(req,{ignoreSearch:true}).then(hit=>hit||c.match('./index.html')))))});
// Other same-origin GET: answer from the cache at once when the exact URL is cached, refresh it in the background.
self.addEventListener('fetch',e=>{const req=e.request,url=new URL(req.url);if(req.method!=='GET'||req.mode==='navigate'||url.origin!==location.origin)return;
 e.respondWith(caches.open(VERSION).then(async cache=>{const hit=await cache.match(req);
  // Exact URL (including ?v=) first, so a new version never gets an old file; any version only when offline.
  const fresh=fetch(req).then(res=>{if(res.ok&&res.type==='basic')cache.put(req,res.clone());return res}).catch(()=>hit||cache.match(req,{ignoreSearch:true}));
  return hit||fresh}))});
`);
console.log('PWA built:',files.length,'files, version',version);
